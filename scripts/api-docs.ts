// FR-096 / T140: the HTTP interface inventory in docs/api.md is generated from the sanitized
// Payload config (every collection, global and root endpoint, built-in and custom) plus the App
// Router route handlers, and marks the Payload built-ins the proxy blocks. `pnpm docs:api` rewrites
// the generated block (scripts/write-api-docs.ts); tests/unit/docs/api-docs.test.ts fails CI when docs/api.md has drifted.
// Semantics (auth, rate limits, responses) are in specs/001-v1-website-cms/contracts/http-surface.md.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import type { SanitizedConfig } from 'payload'

export const DOC = 'docs/api.md'
export const BEGIN = '<!-- api-inventory:begin (generated by `pnpm docs:api`; do not edit) -->'
export const END = '<!-- api-inventory:end -->'
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const METHODS = ['GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'] as const

type Endpoint = { method: string; path: string }
/** Paths Payload adds itself; anything else on a collection/global is project or plugin code. */
const BUILT_IN = new Set([
  '/',
  '/:id',
  '/count',
  '/access/:id?',
  '/access',
  '/versions',
  '/versions/:id',
  '/:id/duplicate',
  '/login',
  '/logout',
  '/me',
  '/refresh-token',
  '/forgot-password',
  '/reset-password',
  '/unlock',
  '/verify/:token',
  '/verify/:id',
  '/init',
  '/first-register',
  '/file/:filename',
  '/paste-url/:id?',
  '/:key',
  '/run',
  '/handle-schedules',
])
const join = (base: string, p: string) => (p === '/' ? base : `${base}${p}`)
const sortEndpoints = (e: Endpoint[]) =>
  [...e].sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))

/** Paths the proxy answers with 404 before Payload sees them (src/proxy.ts). */
export function blockedPaths(): { exact: string[]; prefixes: string[] } {
  const src = fs.readFileSync(path.join(ROOT, 'src/proxy.ts'), 'utf8')
  const list = (name: string, open: string, close: string) => {
    const m = new RegExp(
      `const ${name} = ${open.replace(/[[(]/g, '\\$&')}([\\s\\S]*?)${close.replace(/[\])]/g, '\\$&')}`,
    ).exec(src)
    if (!m) throw new Error(`src/proxy.ts: ${name} not found`)
    return [...m[1]!.matchAll(/'([^']+)'/g)].map((x) => x[1]!)
  }
  return { exact: list('BLOCKED', 'new Set([', '])'), prefixes: list('BLOCKED_PREFIXES', '[', ']') }
}

/** App Router route handlers outside the Payload catch-all: [url path, methods]. */
export function appRoutes(): [string, string[]][] {
  const out: [string, string[]][] = []
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name)
      if (e.isDirectory()) walk(full)
      else if (e.name === 'route.ts') {
        const rel = path.relative(path.join(ROOT, 'src/app'), path.dirname(full))
        const url =
          '/' +
          rel
            .split(path.sep)
            .filter((s) => !/^\(.*\)$/.test(s))
            .join('/')
        if (url === '/api/[...slug]') continue // Payload REST: listed from the config below
        const src = fs.readFileSync(full, 'utf8')
        const methods = METHODS.filter((m) =>
          new RegExp(`export (async )?function ${m}\\b|export const ${m}\\b`).test(src),
        )
        out.push([url, [...methods]])
      }
    }
  }
  walk(path.join(ROOT, 'src/app'))
  return out.sort((a, b) => a[0].localeCompare(b[0]))
}

export function renderInventory(config: SanitizedConfig): string {
  const api = config.routes.api
  const blocked = blockedPaths()
  const isBlocked = (p: string) =>
    blocked.exact.includes(p) ||
    blocked.prefixes.some((x) => p.startsWith(x) || `${p}/`.startsWith(x))
  const row = (method: string, p: string, kind: string) =>
    `| ${method.toUpperCase()} | \`${p}\` | ${kind} | ${isBlocked(p) ? '**blocked (404)**' : ''} |`
  const lines: string[] = [BEGIN, '']
  lines.push(
    `GraphQL: ${config.graphQL?.disable ? 'disabled' : 'enabled'}. REST prefix: \`${api}\`.`,
    '',
  )
  lines.push(
    '### App Router handlers',
    '',
    '| Method | Path | Kind | Proxy |',
    '| --- | --- | --- | --- |',
  )
  for (const [url, methods] of appRoutes())
    for (const m of methods) lines.push(row(m, url, 'route handler'))
  lines.push(
    '',
    '### Root endpoints',
    '',
    '| Method | Path | Kind | Proxy |',
    '| --- | --- | --- | --- |',
  )
  for (const e of sortEndpoints((config.endpoints ?? []) as Endpoint[]))
    lines.push(
      row(e.method, join(api, e.path), BUILT_IN.has(e.path) ? 'Payload built-in' : 'custom'),
    )
  for (const [label, items, prefix] of [
    ['Collections', config.collections, ''],
    ['Globals', config.globals, '/globals'],
  ] as const) {
    lines.push('', `### ${label}`)
    for (const c of items) {
      const eps = sortEndpoints((c.endpoints || []) as Endpoint[])
      const flags = [
        'auth' in c && c.auth ? 'auth' : '',
        'upload' in c && c.upload ? 'upload' : '',
        c.versions
          ? c.versions &&
            typeof c.versions === 'object' &&
            'drafts' in c.versions &&
            c.versions.drafts
            ? 'versions+drafts'
            : 'versions'
          : '',
      ].filter(Boolean)
      lines.push(
        '',
        `#### \`${c.slug}\`${flags.length ? ` (${flags.join(', ')})` : ''}`,
        '',
        '| Method | Path | Kind | Proxy |',
        '| --- | --- | --- | --- |',
      )
      if (!eps.length) lines.push('| — | — | no REST endpoints | |')
      for (const e of eps) {
        const p = join(`${api}${prefix}/${c.slug}`, e.path)
        lines.push(row(e.method, p, BUILT_IN.has(e.path) ? 'Payload built-in' : 'custom'))
      }
    }
  }
  lines.push('', END)
  return lines.join('\n')
}

export function withInventory(doc: string, inventory: string): string {
  const a = doc.indexOf(BEGIN)
  const b = doc.indexOf(END)
  if (a === -1 || b === -1) throw new Error(`${DOC}: generated markers missing`)
  return doc.slice(0, a) + inventory + doc.slice(b + END.length)
}
