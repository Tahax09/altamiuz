// Passkeys (WebAuthn, ADR-012). Like the MFA tables (20261016_143400_auth_tables), these live
// outside Payload collections so no Payload API, query or select can return them. Additive only;
// `down` drops exactly what `up` creates.
//
// - user_passkey_handles: one random WebAuthn user handle per account (never the database id or
//   the e-mail, so an authenticator never learns either).
// - user_passkeys: registered credentials. The public key is not secret, but nothing outside the
//   auth module reads it. credential_id is unique across all accounts.
// - webauthn_challenges: single-use challenges, bound to their purpose and, where a session
//   exists, to that user and session; consumed with DELETE … RETURNING.
// - auth_sessions.auth_method: how the session was opened ('password' or 'passkey'), so a passkey
//   is only accepted as a second step after a password.
//
// Audit actions passkey.register and passkey.remove (generated by Payload). Rolling back past this
// migration fails while audit events with those actions exist: the audit log is append-only and is
// never rewritten to make a rollback possible. Roll back only on a database without them.
import { MigrateUpArgs, MigrateDownArgs, sql } from '@payloadcms/db-postgres'

